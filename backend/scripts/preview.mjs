import mysql from 'mysql2/promise';
import {Database} from '../dist/config/database.js';
import {createApp} from '../dist/app.js';
import {HealthService} from '../dist/services/health.service.js';
import {MySqlHealthRepository} from '../dist/repositories/health.repository.js';
import {AuthService} from '../dist/services/auth.service.js';
import {MySqlUserRepository} from '../dist/repositories/user.repository.js';
import {PasswordService} from '../dist/services/password.service.js';
import {TokenService} from '../dist/services/token.service.js';
import {VehicleService} from '../dist/services/vehicle.service.js';
import {MySqlVehicleRepository} from '../dist/repositories/vehicle.repository.js';
import {FleetService} from '../dist/services/fleet.service.js';
import {MySqlFleetRepository} from '../dist/repositories/fleet.repository.js';
import {BookingService} from '../dist/services/booking.service.js';
import {MySqlBookingRepository} from '../dist/repositories/booking.repository.js';
import {randomBytes} from 'node:crypto';
import {LegalService} from '../dist/services/legal.service.js';
if(process.env.AUTORENT_TEST_PORT!=='3318')throw new Error('Solo instancia temporal.');
const root=await mysql.createConnection({host:'127.0.0.1',port:3318,user:'root',password:''});
const password=randomBytes(24).toString('hex');
await root.query("CREATE USER IF NOT EXISTS 'preview'@'127.0.0.1' IDENTIFIED BY ?",[password]);
await root.query("ALTER USER 'preview'@'127.0.0.1' IDENTIFIED BY ?",[password]);
await root.query("GRANT SELECT,INSERT,UPDATE,DELETE ON autorent_test.* TO 'preview'@'127.0.0.1'");
await root.end();
const database=new Database({host:'127.0.0.1',port:3318,name:'autorent_test',user:'preview',password});
const legal=new LegalService(database);
const auth=new AuthService(new MySqlUserRepository(database),new PasswordService(),new TokenService({secret:randomBytes(32).toString('base64url'),expiresInSeconds:3600}),legal);
const server=createApp(new HealthService(new MySqlHealthRepository(database)),auth,new VehicleService(new MySqlVehicleRepository(database)),new FleetService(new MySqlFleetRepository(database)),new BookingService(new MySqlBookingRepository(database,legal)),{legal,deployment:{origins:['http://127.0.0.1:8080','http://localhost:8080'],proxyHops:0,poolSize:5}}).listen(3001,'127.0.0.1',()=>console.info('Vista de prueba en puerto 3001. Solo base temporal.'));
process.on('SIGINT',()=>server.close(()=>database.close()));
